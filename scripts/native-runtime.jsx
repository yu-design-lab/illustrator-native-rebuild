/* Local Illustrator object writer. No remote recognition, imports, tracing or image nodes. */
(function () {
    var config = NATIVE_REBUILD_CONFIG;
    var layer = null;
    function encode(v) {
        if (v === null) return 'null';
        if (typeof v === 'string') return '"' + v.replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/[\u0000-\u001f]/g,function(c){return '\\u'+('0000'+c.charCodeAt(0).toString(16)).slice(-4);}) + '"';
        if (typeof v === 'number' || typeof v === 'boolean') return String(v);
        var parts = [], k;
        if (v instanceof Array) { for(k=0;k<v.length;k++)parts.push(encode(v[k])); return '['+parts.join(',')+']'; }
        for(k in v)if(v.hasOwnProperty(k))parts.push(encode(k)+':'+encode(v[k]));
        return '{'+parts.join(',')+'}';
    }
    function fail(message) { throw new Error(message); }
    function normalized(p) { return String(p).replace(/\\/g,'/').toLowerCase(); }
    function fullName(d) { try{return d.fullName.fsName;}catch(ignore){return null;} }
    function description(d) {
        var a=d.artboards.getActiveArtboardIndex();
        return {name:d.name,path:fullName(d),artboardIndex:a,artboardRect:d.artboards[a].artboardRect,
            pageItems:d.pageItems.length,layers:d.layers.length};
    }
    try {
        if (!app.documents.length) fail('No Illustrator document is open');
        if (config.operation === 'inspect') {
            var descriptions=[];
            for(var di=0;di<app.documents.length;di++) descriptions.push(description(app.documents[di]));
            return encode({ok:true,operation:'inspect',active:description(app.activeDocument),documents:descriptions});
        }
        if(config.operation !== 'draw') fail('Unsupported operation');
        var source=new File(config.scenePath); source.encoding='UTF-8';
        if(!source.open('r'))fail('Cannot read prepared scene');
        var raw=source.read();source.close();
        // Only validated JSON generated by native-rebuild.cjs enters this local reader.
        var scene=eval('('+raw+')');
        var doc=null;
        for(var i=0;i<app.documents.length;i++) {
            var candidate=app.documents[i];
            if(candidate.name===scene.document || (fullName(candidate) && normalized(fullName(candidate))===normalized(scene.document))) {
                if(doc!==null)fail('Ambiguous document name; use its full path'); doc=candidate;
            }
        }
        if(doc===null)fail('The specified target document is not open');
        if(app.activeDocument!==doc)fail('The specified target document must be active');
        for(i=0;i<doc.layers.length;i++)if(doc.layers[i].name===scene.layer)fail('Layer already exists; inspect partial artwork before continuing');
        var outputAi=new File(scene.outputAi), outputPng=new File(scene.outputPng);
        if(outputAi.exists && normalized(fullName(doc))!==normalized(outputAi.fsName))fail('AI output already exists and is not the current document');
        if(outputPng.exists)fail('PNG output already exists; choose a new preview path');
        if(!outputAi.parent.exists || !outputPng.parent.exists)fail('Create output directories before drawing');
        function checkFonts(objects) {
            for(var j=0;j<objects.length;j++) {
                var o=objects[j];
                if(o.type==='text')app.textFonts.getByName(o.font);
                if(o.type==='group')checkFonts(o.children);
            }
        }
        checkFonts(scene.objects); // Fail before changing the document if a font is unavailable.
        var rect=doc.artboards[doc.artboards.getActiveArtboardIndex()].artboardRect;
        var scale=scene.scale;
        function xy(p){return [rect[0]+scene.origin[0]+p[0]*scale,rect[1]-scene.origin[1]-p[1]*scale];}
        function solid(c) {
            if(typeof c==='string') {var rgb=new RGBColor();rgb.red=parseInt(c.substr(1,2),16);rgb.green=parseInt(c.substr(3,2),16);rgb.blue=parseInt(c.substr(5,2),16);return rgb;}
            var ink=new CMYKColor();ink.cyan=c.cmyk[0];ink.magenta=c.cmyk[1];ink.yellow=c.cmyk[2];ink.black=c.cmyk[3];return ink;
        }
        var nativeGradients={};
        layer=doc.layers.add();layer.name=scene.layer;
        for(i=0;i<scene.gradients.length;i++) {
            var definition=scene.gradients[i],gradient=doc.gradients.add();
            gradient.name=scene.layer+'__'+definition.id;
            gradient.type=definition.type==='radial'?GradientType.RADIAL:GradientType.LINEAR;
            while(gradient.gradientStops.length<definition.stops.length)gradient.gradientStops.add();
            while(gradient.gradientStops.length>definition.stops.length)gradient.gradientStops[gradient.gradientStops.length-1].remove();
            for(var st=0;st<definition.stops.length;st++) {
                var stop=gradient.gradientStops[st],spec=definition.stops[st];
                stop.rampPoint=spec.offset;stop.color=solid(spec.color);stop.opacity=spec.opacity===undefined?100:spec.opacity;
            }
            nativeGradients['$'+definition.id]=gradient;
        }
        function fillColor(c) {
            if(c.gradient!==undefined) {
                var gc=new GradientColor();gc.gradient=nativeGradients['$'+c.gradient];
                gc.origin=xy(c.origin);gc.length=c.length*scale;
                // Use a native matrix: Illustrator's GradientColor.angle setter is unreliable.
                gc.matrix=app.getRotationMatrix(c.angle);
                return gc;
            }
            return solid(c);
        }
        var stats={groups:0,paths:0,compounds:0,textFrames:0,gradientFills:0,raster:0,placed:0};
        function appearance(item,o) {
            item.filled=o.fill!==undefined&&o.fill!==null;
            if(item.filled) {item.fillColor=fillColor(o.fill);if(o.fill.gradient!==undefined)stats.gradientFills++;}
            item.stroked=o.stroke!==undefined&&o.stroke!==null;
            if(item.stroked) {item.strokeColor=solid(o.stroke);item.strokeWidth=(o.strokeWidth===undefined?1:o.strokeWidth)*scale;}
            if(o.opacity!==undefined)item.opacity=o.opacity;
        }
        function makePath(parent,o,compoundRule) {
            var p=parent.pathItems.add();p.name=o.name;
            for(var pi=0;pi<o.points.length;pi++) {
                var q=o.points[pi],pp=p.pathPoints.add();
                pp.anchor=xy(q.anchor);pp.leftDirection=xy(q.left||q.anchor);pp.rightDirection=xy(q.right||q.anchor);
                pp.pointType=q.smooth?PointType.SMOOTH:PointType.CORNER;
            }
            p.closed=o.closed===true;p.evenodd=compoundRule===true||o.evenodd===true;stats.paths++;
            return p;
        }
        function draw(o,parent) {
            var item,j;
            if(o.type==='group') {
                item=parent.groupItems.add();item.name=o.name;stats.groups++;
                for(j=0;j<o.children.length;j++)draw(o.children[j],item);
                if(o.opacity!==undefined)item.opacity=o.opacity;
            } else if(o.type==='text') {
                item=parent.textFrames.add();item.name=o.name;item.contents=o.text;
                item.textRange.characterAttributes.textFont=app.textFonts.getByName(o.font);
                item.textRange.characterAttributes.size=o.size*scale;
                item.textRange.characterAttributes.fillColor=solid(o.fill);
                var alignment=o.align||'left';
                item.textRange.paragraphAttributes.justification=alignment==='center'?Justification.CENTER:(alignment==='right'?Justification.RIGHT:Justification.LEFT);
                // TextFrame.anchor is the point-text baseline; .position would use visible bounds.
                item.anchor=xy(o.position);
                if(o.rotation)item.rotate(o.rotation);
                if(o.opacity!==undefined)item.opacity=o.opacity;stats.textFrames++;
            } else if(o.type==='compound') {
                item=parent.compoundPathItems.add();item.name=o.name;stats.compounds++;
                for(j=0;j<o.paths.length;j++) {var sub=makePath(item,o.paths[j],o.evenodd);appearance(sub,o);}
                if(o.opacity!==undefined)item.opacity=o.opacity;
            } else {
                if(o.type==='path')item=makePath(parent,o,false);
                else {
                    var start=xy([o.box[0],o.box[1]]);
                    if(o.type==='ellipse')item=parent.pathItems.ellipse(start[1],start[0],o.box[2]*scale,o.box[3]*scale);
                    else if(o.type==='rect')item=parent.pathItems.rectangle(start[1],start[0],o.box[2]*scale,o.box[3]*scale);
                    else fail('Unsupported native object');
                    stats.paths++;
                }
                item.name=o.name;appearance(item,o);
            }
            // Later source objects remain above earlier objects, within every semantic group.
            item.zOrder(ZOrderMethod.BRINGTOFRONT);
            return item;
        }
        for(i=0;i<scene.objects.length;i++){draw(scene.objects[i],layer);if((i+1)%25===0)app.redraw();}
        app.redraw();
        function audit(container) {
            for(var j=0;j<container.pageItems.length;j++) {
                var p=container.pageItems[j];
                if(p.parent!==container)continue;
                if(p.typename==='RasterItem')stats.raster++;
                if(p.typename==='PlacedItem')stats.placed++;
                if(p.typename==='GroupItem')audit(p);
            }
        }
        audit(layer);
        if(stats.raster||stats.placed)fail('Unexpected raster or placed object in the new layer');
        if(fullName(doc) && normalized(fullName(doc))===normalized(outputAi.fsName))doc.save();
        else {var saveOptions=new IllustratorSaveOptions();saveOptions.pdfCompatible=true;doc.saveAs(outputAi,saveOptions);}
        var pngOptions=new ExportOptionsPNG24();pngOptions.artBoardClipping=true;pngOptions.transparency=false;
        pngOptions.horizontalScale=200;pngOptions.verticalScale=200;
        doc.exportFile(outputPng,ExportType.PNG24,pngOptions);
        if(!outputAi.exists||!outputPng.exists)fail('Expected AI or PNG file was not created');
        return encode({ok:true,operation:'draw',document:doc.name,layer:layer.name,ai:outputAi.fsName,png:outputPng.fsName,
            counts:stats,visualChecked:false});
    } catch(error) {
        return encode({ok:false,error:String(error),partialLayer:layer?layer.name:null,visualChecked:false});
    }
}());
